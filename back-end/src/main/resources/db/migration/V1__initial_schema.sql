-- Schema inicial do ContaDash (PostgreSQL)
-- Nomes físicos seguem a convenção CamelCase -> snake_case do Spring Boot.

CREATE TABLE role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(255)
);

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(60) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE user_profile (
    user_id BIGINT NOT NULL,
    profile_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, profile_id),
    CONSTRAINT fk_user_profile_user FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT fk_user_profile_profile FOREIGN KEY (profile_id) REFERENCES role (id)
);

CREATE TABLE customer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cnpj VARCHAR(18) NOT NULL UNIQUE,
    corporate_name VARCHAR(200) NOT NULL,
    responsible VARCHAR(150),
    email VARCHAR(150),
    full_address VARCHAR(500),
    pending_status VARCHAR(30) NOT NULL,
    last_posted_on TIMESTAMP
);

CREATE TABLE document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    document_type VARCHAR(100) NOT NULL,
    competence VARCHAR(7) NOT NULL,
    due_date DATE,
    direction VARCHAR(30) NOT NULL,
    send_channel VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,
    file_format VARCHAR(10) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    storage_path VARCHAR(500) NOT NULL,
    created_in TIMESTAMP NOT NULL,
    CONSTRAINT fk_document_customer FOREIGN KEY (customer_id) REFERENCES customer (id)
);

CREATE TABLE deadline (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    obligation VARCHAR(255) NOT NULL,
    category VARCHAR(100),
    competence VARCHAR(7),
    due_date DATE NOT NULL,
    priority VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    delivered_on TIMESTAMP,
    current_stage VARCHAR(50),
    update_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_deadline_customer FOREIGN KEY (customer_id) REFERENCES customer (id)
);

CREATE TABLE request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    title VARCHAR(150) NOT NULL,
    competence VARCHAR(7) NOT NULL,
    deadline DATE NOT NULL,
    status VARCHAR(30) NOT NULL,
    created_in TIMESTAMP NOT NULL,
    completed_in TIMESTAMP,
    cancelled_in TIMESTAMP,
    CONSTRAINT fk_request_customer FOREIGN KEY (customer_id) REFERENCES customer (id)
);

CREATE TABLE checklist_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(255) NOT NULL,
    format_file_expected VARCHAR(255),
    status VARCHAR(30) NOT NULL,
    name_file_sent VARCHAR(255),
    uploaded_document_id BIGINT,
    submited_on TIMESTAMP,
    revised_on TIMESTAMP,
    reason_refusal VARCHAR(255),
    request_id BIGINT NOT NULL,
    CONSTRAINT fk_checklist_item_request FOREIGN KEY (request_id) REFERENCES request (id),
    CONSTRAINT fk_checklist_item_document FOREIGN KEY (uploaded_document_id) REFERENCES document (id)
);

-- Índices para listagens e contagens (RNF10)
CREATE INDEX idx_document_customer_id ON document (customer_id);
CREATE INDEX idx_document_direction_status ON document (direction, status);
CREATE INDEX idx_document_created_in ON document (created_in DESC);

CREATE INDEX idx_deadline_customer_id ON deadline (customer_id);
CREATE INDEX idx_deadline_due_date ON deadline (due_date);
CREATE INDEX idx_deadline_status ON deadline (status);

CREATE INDEX idx_request_customer_id ON request (customer_id);
CREATE INDEX idx_checklist_item_request_id ON checklist_item (request_id);
